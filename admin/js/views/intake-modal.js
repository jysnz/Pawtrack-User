/**
 * PawTrack Admin — Scan & intake dialog (used by the Impoundments page)
 *
 * Tap an NFC collar tag and the intake form fills itself in.
 *
 * WHAT AN NFC TAG CARRIES (the "payload", see parseTag)
 *   A PawTrack tag holds one NDEF URL record: https://<site>/?nfc=PT-XXXXXXXX. It does NOT hold pet details
 *   (a tag is public, and tags are tiny), only the ID that points to them. The reader also reports the chip's
 *   hardware serial. So the payload is:
 *     tagId   "PT-AB12CD34"   the PawTrack tag ID from the link (preferred key)
 *     serial  "04:A1:B2:C3"   the chip's hardware serial (fallback key, also how foreign tags are matched)
 *     url     the full link that was read (null when the tag had none)
 *     source  'pawtrack-link' | 'serial' | 'manual' | 'none'
 *
 * WHAT THE ID LOOKS UP (the pet record, registered_pets, see adminStore.getPetByRFID: by tagId or serial)
 *   id, name, species, breed, age, gender, color, status (safe|lost|impounded|reunited), photoUrl, microchipNo,
 *   medicalNotes, owner { name, phone, email, address }
 *
 * HOW THAT FILLS THE FORM (see buildDraft)
 *   pet.name -> Name · pet.species/breed/age -> Species/Breed/Age · pet.photoUrl -> Photo
 *   pet.medicalNotes -> Health observations · pet.owner -> Guardian card (who is alerted)
 *   pet.status 'lost' -> "reported missing" notice (a penalty ticket is decided when the intake is saved)
 *   tagId (or serial) + pet.id -> the intake's tag and pet link
 *   Generated by PawTrack, not by the tag: intake time, 72h claim deadline, next free cage, receiving officer.
 *   An unknown tag still fills the tag code and asks for the rest (stray). No tag: manual entry.
 *   A pet that is already in holding is flagged and cannot be logged twice.
 */

window.IntakeModal = {
  root: null,
  opts: {},
  draft: null,
  nfc: { state: 'idle', text: '' },
  _abort: null,

  esc(v) {
    return String(v == null ? '' : v).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  },

  // ===== The NFC payload =====
  parseTag(message, serial) {
    const clean = String(serial || '').trim().toUpperCase() || null;
    if (message && message.records) {
      for (const record of message.records) {
        if (record.recordType !== 'url' && record.recordType !== 'text') continue;
        try {
          const text = new TextDecoder().decode(record.data);
          const match = text.match(/[?&]nfc=([A-Za-z0-9-]+)/);
          if (match) return { tagId: match[1].toUpperCase(), serial: clean, url: text, source: 'pawtrack-link' };
        } catch (e) { /* unreadable record: try the next */ }
      }
    }
    return clean ? { tagId: null, serial: clean, url: null, source: 'serial' } : null;
  },

  // Something typed by hand is a tag ID, a chip serial or a microchip number: all are looked up the same way
  manualPayload(raw) {
    const code = String(raw || '').trim().toUpperCase();
    if (!code) return null;
    return { tagId: /^PT-/.test(code) ? code : null, serial: /^PT-/.test(code) ? null : code, url: null, source: 'manual' };
  },

  // ===== From a payload to a filled-in form =====
  facilities() {
    const store = window.adminStore;
    const ids = typeof store.getMyFacilityIds === 'function' ? store.getMyFacilityIds() : [];
    const all = typeof store.getShelters === 'function' ? store.getShelters() : [];
    const list = all.filter(s => ids.includes(s.id));
    const me = store.getMyShelter();
    return list.length ? list : (me ? [me] : []);
  },

  speciesOf(v) {
    const s = String(v || '').toLowerCase();
    return /dog|aso|canine/.test(s) ? 'Dog' : /cat|pusa|feline/.test(s) ? 'Cat' : s ? 'Other' : 'Dog';
  },

  // The smallest "Cage N" that nobody in that facility is using
  nextCage(facilityId) {
    const used = new Set();
    (window.adminStore.getImpoundments ? window.adminStore.getImpoundments() : []).forEach(i => {
      if (i.shelterId !== facilityId || i.status !== 'active_impounded') return;
      const n = parseInt(String(i.cageNumber || '').replace(/\D+/g, ''), 10);
      if (Number.isFinite(n)) used.add(n);
    });
    let n = 1;
    while (used.has(n)) n++;
    return `Cage ${n}`;
  },

  heldNow(pet, tag) {
    const list = window.adminStore.getImpoundments ? window.adminStore.getImpoundments() : [];
    return list.find(i => i.status === 'active_impounded' && ((pet && i.petId && i.petId === pet.id) || (tag && i.rfidTag && String(i.rfidTag).toUpperCase() === tag))) || null;
  },

  buildDraft(payload, facilityId) {
    const store = window.adminStore;
    const tagId = payload ? payload.tagId : null;
    const serial = payload ? payload.serial : null;
    const pet = (tagId && store.getPetByRFID(tagId)) || (serial && store.getPetByRFID(serial)) || null;
    const code = (pet && pet.rfidTag) || tagId || serial || '';
    const owner = pet && pet.owner ? pet.owner : null;
    const now = Date.now();
    return {
      match: pet ? 'registered' : (payload ? 'unregistered' : 'none'),
      payload: payload || null,
      tag: code,
      petId: pet ? pet.id : null,
      petName: pet ? pet.name : '',
      species: this.speciesOf(pet && pet.species),
      breed: pet ? pet.breed || '' : '',
      age: pet ? pet.age || '' : '',
      photoUrl: pet ? pet.photoUrl || '' : '',
      healthCondition: pet ? pet.medicalNotes || '' : '',
      guardian: owner && (owner.name || owner.phone) ? { name: owner.name || '', phone: owner.phone || '', email: owner.email || '' } : null,
      missing: !!pet && (pet.status === 'lost' || pet.status === 'missing'),
      alreadyHeld: this.heldNow(pet, code.toUpperCase()),
      cageNumber: this.nextCage(facilityId),
      intakeOfficer: (store.currentAdmin() || {}).full_name || '',
      intakeAt: new Date(now).toISOString(),
      claimDeadline: new Date(now + 72 * 3600 * 1000).toISOString()
    };
  },

  // ===== The dialog =====
  open(opts = {}) {
    const store = window.adminStore;
    const mine = store.getMyShelter();
    this.opts = opts;
    if (!mine) return this.openNoFacility();

    const tree = this.facilities();
    const wanted = opts.facilityId || (window.ImpoundmentsView && window.ImpoundmentsView.facilityFilter);
    this.facilityId = tree.some(s => s.id === wanted) ? wanted : mine.id;
    this.draft = null;
    this.stopNfc();

    const root = window.adminApp.openModalContent(`
      <div class="modal-header">
        <div class="nock-card-title">Scan &amp; intake</div>
        <button class="icon-btn-subtle" id="in-close" aria-label="Close">&times;</button>
      </div>
      <div class="modal-body" id="in-body"></div>`);
    this.root = root;
    root.querySelector('#in-close').addEventListener('click', () => this.close());
    this.renderScan();
    // Start listening at once: the tap that opened this dialog counts as the user's go-ahead
    if (this.nfcSupported() && !opts.noAuto) this.startNfc();
  },

  close() {
    this.stopNfc();
    if (this.picker) { try { this.picker.destroy(); } catch (e) { /* gone */ } this.picker = null; }
    this.pickup = null;
    this.draft = null;
    window.adminApp.closeModal();
  },

  openNoFacility() {
    const reload = () => window.adminApp.renderView(window.adminApp.currentRoute || 'impoundments');
    const box = window.adminApp.openModalContent(`
      <div class="modal-header"><div class="nock-card-title">Scan &amp; intake</div><button class="icon-btn-subtle" id="in-close" aria-label="Close">&times;</button></div>
      <div class="modal-body" style="text-align:center;padding:28px 8px;">
        <div style="font-weight:700;font-size:15px;color:var(--ink-primary);margin-bottom:6px;">Set up your impound facility first</div>
        <div style="font-size:12.5px;color:var(--ink-muted);line-height:1.55;max-width:380px;margin:0 auto;">An intake is logged into the facility you work for. Register yours or join with an invite code, then come back.</div>
      </div>
      <div class="modal-footer">
        <button class="btn btn-secondary" id="in-join">Join with invite code</button>
        <button class="btn btn-primary" id="in-add">Register your facility</button>
      </div>`);
    box.querySelector('#in-close').addEventListener('click', () => window.adminApp.closeModal());
    box.querySelector('#in-add').addEventListener('click', () => { window.adminApp.closeModal(); window.SheltersView.openShelterModal(null, { onCreated: reload }); });
    box.querySelector('#in-join').addEventListener('click', () => { window.adminApp.closeModal(); window.SheltersView.openJoinModal({ onJoined: reload }); });
  },

  // Which facility receives the pet: a choice only when this account works with more than one
  facilityPickHtml() {
    const tree = this.facilities();
    if (tree.length < 2) return '';
    return `
      <div class="form-group">
        <label class="form-label" for="in-fac">Receiving facility</label>
        <select class="form-control" id="in-fac" name="shelterId">${tree.map(s => `<option value="${this.esc(s.id)}" ${s.id === this.facilityId ? 'selected' : ''}>${this.esc(s.name)}</option>`).join('')}</select>
      </div>`;
  },

  bindFacility(scope) {
    scope.querySelector('#in-fac')?.addEventListener('change', (e) => {
      this.facilityId = e.target.value;
      const cage = scope.querySelector('#in-cage');
      if (cage && cage.dataset.auto === '1') cage.value = this.nextCage(this.facilityId);
    });
  },

  // ----- Step 1: tap the tag -----
  renderScan() {
    const body = this.root.querySelector('#in-body');
    body.innerHTML = `
      <p class="trm-lead" style="margin:0 0 14px;">Hold the pet's NFC collar tag to the back of this device. The form fills itself in from the tag.</p>
      <div class="trm-scan-form" style="display:flex;gap:8px;flex-wrap:wrap;">
        <button type="button" class="btn btn-primary trm-nfc-btn" id="in-nfc-btn" aria-pressed="false">
          <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M6 8.3a6 6 0 0 1 0 7.4M10 5.5a10 10 0 0 1 0 13M14 3a14 14 0 0 1 0 18"/></svg>
          <span>Tap NFC</span>
        </button>
      </div>
      <div id="in-nfc" class="trm-nfc" role="status" aria-live="polite" hidden><i aria-hidden="true"></i><span></span></div>
      <form class="trm-scan-form trm-code-form" id="in-code-form" style="margin-top:12px;" autocomplete="off">
        <input type="text" class="form-control" id="in-code" maxlength="60" placeholder="Or type the tag code (e.g. PT-ABC12345)" aria-label="Tag code" />
        <button type="submit" class="btn btn-secondary">Look up</button>
      </form>
      ${this.facilityPickHtml() ? `<div style="margin-top:14px;">${this.facilityPickHtml()}</div>` : ''}
      <p class="trm-notag">Pet has no tag? <button type="button" class="trm-link" id="in-notag">Log it without NFC</button></p>`;

    body.querySelector('#in-nfc-btn').addEventListener('click', () => (this.nfc.state === 'scanning' ? this.stopNfc() : this.startNfc()));
    body.querySelector('#in-notag').addEventListener('click', () => this.showForm(null));
    body.querySelector('#in-code-form').addEventListener('submit', (e) => {
      e.preventDefault();
      const payload = this.manualPayload(body.querySelector('#in-code').value);
      if (!payload) { this.setNfc('error', 'Type the tag code first.'); return; }
      this.stopNfc();
      this.showForm(payload);
    });
    this.bindFacility(body);
    this.paintNfc();
  },

  // ----- Step 2: the form, already filled in -----
  showForm(payload) {
    this.holdNfc();
    this.draft = this.buildDraft(payload, this.facilityId);
    if (payload && window.adminStore.logAction) {
      window.adminStore.logAction('Intake Scan', this.draft.petId ? `Tag ${this.draft.tag} read for ${this.draft.petName}` : `Unregistered tag ${this.draft.tag} read`);
    }
    this.renderForm();
  },

  renderForm() {
    const d = this.draft;
    const registered = d.match === 'registered';
    const blocked = !!d.alreadyHeld;
    const g = d.guardian;
    const tagLine = [d.payload && d.payload.tagId ? `Tag ${d.payload.tagId}` : '', d.payload && d.payload.serial ? `Chip ${d.payload.serial}` : ''].filter(Boolean).join(' · ');
    const body = this.root.querySelector('#in-body');

    const title = registered ? this.esc(d.petName)
      : d.match === 'unregistered' ? 'Tag not registered'
      : 'Pet without a tag';
    const sub = registered
      ? `${this.esc([d.species, d.breed, d.age].filter(Boolean).join(' · '))}${g ? `<br>Guardian ${this.esc(g.name || 'unknown')}${g.phone ? ' · ' + this.esc(g.phone) : ''} (will be alerted)` : '<br>No guardian contact on file'}`
      : d.match === 'unregistered'
        ? `${this.esc(d.tag)} is not linked to a pet. Add what you can see and log it as a stray.`
        : 'Add what you can see. Owners will find it in this facility\'s list of pets.';

    body.innerHTML = `
      <div class="trm-match ${registered ? 'is-found' : 'is-new'}">
        ${registered && d.photoUrl ? `<img src="${this.esc(d.photoUrl)}" class="pet-thumb" alt="" />` : `<span class="trm-match-ic" aria-hidden="true">${registered ? '✓' : d.match === 'none' ? '+' : '?'}</span>`}
        <div class="trm-match-text"><b>${title}</b><small>${sub}</small>${tagLine ? `<small style="font-family:var(--font-mono);">${this.esc(tagLine)}</small>` : ''}</div>
        <button type="button" class="trm-link" id="in-reset">Scan again</button>
      </div>
      ${blocked ? `<div class="trm-nfc" data-state="error" role="alert" style="margin-top:12px;"><i aria-hidden="true"></i><span>${this.esc(d.petName || 'This pet')} is already in holding at ${this.esc(d.alreadyHeld.shelterName || 'a facility')} (${this.esc(d.alreadyHeld.cageNumber || 'no cage')}). Release or close that case first.</span></div>` : ''}
      ${d.missing && !blocked ? `<div class="trm-nfc" data-state="scanning" role="status" style="margin-top:12px;"><i aria-hidden="true"></i><span>${this.esc(d.petName)} was reported missing. Logging this intake can issue the guardian a penalty ticket.</span></div>` : ''}
      <div class="trm-result" style="margin-top:0;">
        <form id="in-form" class="trm-form" novalidate>
          <div class="trm-sec">Pet details</div>
          <div class="trm-row">
            <div class="form-group"><label class="form-label" for="in-name">Name or identifier <span class="trm-req" aria-hidden="true">*</span></label>
              <input type="text" class="form-control" id="in-name" name="petName" value="${this.esc(d.petName)}" placeholder="e.g. Unidentified dog" required /></div>
            <div class="form-group"><label class="form-label" for="in-species">Species</label>
              <select class="form-control" id="in-species" name="species">${['Dog', 'Cat', 'Other'].map(s => `<option value="${s}" ${d.species === s ? 'selected' : ''}>${s}</option>`).join('')}</select></div>
          </div>
          <div class="trm-row">
            <div class="form-group"><label class="form-label" for="in-breed">Breed <span class="trm-opt">optional</span></label>
              <input type="text" class="form-control" id="in-breed" name="breed" value="${this.esc(d.breed)}" placeholder="e.g. Aspin, Shih Tzu" /></div>
            <div class="form-group"><label class="form-label" for="in-age">Age <span class="trm-opt">optional</span></label>
              <input type="text" class="form-control" id="in-age" name="age" value="${this.esc(d.age)}" placeholder="e.g. 2 yrs, 6 mo" /></div>
          </div>
          <div class="form-group" id="in-photo-group">
            <span class="form-label" id="in-photo-label">Photo <span class="trm-req" aria-hidden="true">*</span> <span class="trm-opt">shown to owners</span></span>
            <div class="trm-photo2 ${registered && d.photoUrl ? 'has-photo' : ''}" role="group" aria-labelledby="in-photo-label">
              <div class="trm-photo2-prev">
                <img id="in-photo-prev" alt="Photo of the pet" ${registered && d.photoUrl ? `src="${this.esc(d.photoUrl)}"` : 'hidden'} />
                <svg class="trm-photo2-ph" width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M23 19a2 2 0 0 1-2 2H3a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h4l2-3h6l2 3h4a2 2 0 0 1 2 2z"/><circle cx="12" cy="13" r="4"/></svg>
              </div>
              <div class="trm-photo2-body">
                <b id="in-photo-title">${registered && d.photoUrl ? 'Photo from the pet\'s profile' : 'Add a clear photo of the pet'}</b>
                <small>Owners use this photo to recognise their pet. Show the face, and the whole body if you can.</small>
                <div class="trm-photo2-actions">
                  <label class="btn btn-secondary btn-sm" for="in-photo-cam" tabindex="0" id="in-photo-cam-btn">
                    <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M23 19a2 2 0 0 1-2 2H3a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h4l2-3h6l2 3h4a2 2 0 0 1 2 2z"/><circle cx="12" cy="13" r="4"/></svg>
                    Take photo
                  </label>
                  <label class="btn btn-secondary btn-sm" for="in-photo" tabindex="0">
                    <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4M17 8l-5-5-5 5M12 3v12"/></svg>
                    Upload
                  </label>
                </div>
                <span class="trm-photo2-name" id="in-photo-name" hidden></span>
              </div>
              <input type="file" class="trm-photo-input" id="in-photo-cam" accept="image/*" capture="environment" tabindex="-1" />
              <input type="file" class="trm-photo-input" id="in-photo" name="photo" accept="image/*" tabindex="-1" />
            </div>
            <p class="trm-photo-err" id="in-photo-err" role="alert" hidden>Add a photo of the pet to log the intake.</p>
          </div>
          <div class="trm-sec">Intake</div>
          ${this.facilityPickHtml()}
          <div class="trm-row">
            <div class="form-group"><label class="form-label" for="in-cage">Cage number <span class="trm-req" aria-hidden="true">*</span></label>
              <input type="text" class="form-control" id="in-cage" name="cageNumber" value="${this.esc(d.cageNumber)}" data-auto="1" required /></div>
            <div class="form-group"><label class="form-label" for="in-officer">Receiving officer</label>
              <input type="text" class="form-control" id="in-officer" name="intakeOfficer" value="${this.esc(d.intakeOfficer)}" /></div>
          </div>
          <div class="form-group" id="in-pickup">
            <label class="form-label" for="in-loc-search">Pickup location <span class="trm-opt">optional, pin where the animal was found</span></label>
            <div class="fm-address-row">
              <input type="text" class="form-control" id="in-loc-search" placeholder="Search a street, landmark or barangay" autocomplete="off" />
              <button type="button" class="btn btn-secondary" id="in-loc-find">Find on map</button>
            </div>
            <div id="in-map" class="fm-map trm-map"><div class="shm-fallback">Loading map…</div></div>
            <div class="trm-pin-status" id="in-pin-status" aria-live="polite">Click the map or drag the pin to the spot where the animal was picked up.</div>
          </div>
          <div class="form-group"><label class="form-label" for="in-loc-desc">Place description <span class="trm-opt">optional</span></label>
            <input type="text" class="form-control" id="in-loc-desc" name="placeDescription" maxlength="160" placeholder="e.g. Beside the 7-Eleven, near the barangay hall" /></div>
          <div class="form-group"><label class="form-label" for="in-health">Health observations <span class="trm-opt">optional</span></label>
            <textarea class="form-control" id="in-health" name="healthCondition" rows="2" placeholder="e.g. Active, healthy, collar tag verified">${this.esc(d.healthCondition)}</textarea></div>
          <div class="trm-note"><svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><circle cx="12" cy="12" r="10"/><path d="M12 6v6l4 2"/></svg>
            <span>Holding starts now. The 72-hour claim window closes <b>${this.esc(new Date(d.claimDeadline).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' }))}</b>.</span></div>
        </form>
      </div>
      <div class="modal-footer trm-foot">
        <button class="btn btn-secondary" id="in-cancel">Cancel</button>
        <button class="btn btn-primary" id="in-submit" ${blocked ? 'disabled' : ''}>Log intake${registered && g ? ' and alert guardian' : ''}</button>
      </div>`;

    const form = body.querySelector('#in-form');
    body.querySelector('#in-cage').addEventListener('input', (e) => { e.target.dataset.auto = '0'; });
    body.querySelector('#in-reset').addEventListener('click', () => { this.draft = null; this.renderScan(); if (this.nfcSupported()) this.startNfc(); });
    body.querySelector('#in-cancel').addEventListener('click', () => this.close());
    body.querySelector('#in-submit').addEventListener('click', () => {
      if (!form.checkValidity()) { form.reportValidity(); return; }
      if (this.photoRequired && !this.photoRequired()) return;
      this.submit(form);
    });
    form.addEventListener('submit', (e) => e.preventDefault());
    // Photo: the camera and the upload button both fill the one "photo" field; a photo is required
    const main = body.querySelector('#in-photo');
    const cam = body.querySelector('#in-photo-cam');
    const box = body.querySelector('.trm-photo2');
    const prev = body.querySelector('#in-photo-prev');
    const hasPhoto = () => !!(main.files && main.files[0]) || !!(registered && d.photoUrl);
    const showPhoto = (f) => {
      if (!f || !/^image\//.test(f.type || '')) return;
      if (prev._url) URL.revokeObjectURL(prev._url);
      prev._url = URL.createObjectURL(f);
      prev.src = prev._url; prev.hidden = false;
      box.classList.add('has-photo'); box.classList.remove('is-invalid');
      body.querySelector('#in-photo-title').textContent = 'Photo added';
      const nm = body.querySelector('#in-photo-name');
      nm.textContent = f.name.length > 34 ? f.name.slice(0, 31) + '...' : f.name; nm.hidden = false;
      body.querySelector('#in-photo-err').hidden = true;
    };
    main.addEventListener('change', () => showPhoto(main.files && main.files[0]));
    cam.addEventListener('change', () => {
      const f = cam.files && cam.files[0];
      if (!f) return;
      try { const dt = new DataTransfer(); dt.items.add(f); main.files = dt.files; } catch (e) { /* older browsers: keep the camera file only for the preview */ }
      showPhoto(f);
    });
    body.querySelectorAll('.trm-photo2-actions label').forEach((l) => l.addEventListener('keydown', (e) => { if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); l.click(); } }));
    this.photoRequired = () => {
      if (hasPhoto()) return true;
      box.classList.add('is-invalid');
      body.querySelector('#in-photo-err').hidden = false;
      body.querySelector('#in-photo-group').scrollIntoView({ block: 'center', behavior: 'smooth' });
      body.querySelector('#in-photo-cam-btn')?.focus({ preventScroll: true });
      return false;
    };
    this.bindFacility(body);
    this.setupPickupMap(body);
    body.querySelector(registered ? '#in-cage' : '#in-name')?.focus({ preventScroll: true });
  },

  // Pickup location: a Google Map (the same picker as the facility form) to pin the spot, plus an address search.
  // The typed place description is kept separately and saved together with the map address.
  setupPickupMap(body) {
    if (this.picker) { try { this.picker.destroy(); } catch (e) { /* gone */ } this.picker = null; }
    this.pickup = null;
    const FF = window.FacilityForm;
    const mapEl = body.querySelector('#in-map');
    if (!FF || !FF.MapPicker || !mapEl) return;
    const status = body.querySelector('#in-pin-status');
    const search = body.querySelector('#in-loc-search');
    const findBtn = body.querySelector('#in-loc-find');
    const say = (t) => { status.textContent = t; };
    let autoFilled = false;

    const onPick = async (pos) => {
      this.pickup = { lat: pos.lat, lng: pos.lng, address: '' };
      say('Pin placed. Drag it to adjust.');
      if (!this.picker || !this.picker.canGeocode) return;
      const place = await this.picker.reverse(pos);
      if (!place || !this.pickup || this.pickup.lat !== pos.lat || this.pickup.lng !== pos.lng) return;
      this.pickup.address = place.address;
      say(`Pin placed near ${place.address}`);
      if (!search.value.trim() || autoFilled) { search.value = place.address; autoFilled = true; }
    };

    const find = async () => {
      const text = search.value.trim();
      if (!text) { search.focus(); return; }
      if (!this.picker || !this.picker.canGeocode) return;
      findBtn.disabled = true; findBtn.textContent = 'Finding…';
      const found = await this.picker.geocode(`${text}, Philippines`);
      findBtn.disabled = false; findBtn.textContent = 'Find on map';
      if (!found) { say('We could not find that place. Check the spelling, or click the map to place the pin yourself.'); return; }
      autoFilled = false;
      this.picker.setPin({ lat: found.lat, lng: found.lng }, 17);
      this.pickup = { lat: found.lat, lng: found.lng, address: found.address || text };
      say(`Pin placed near ${this.pickup.address}`);
    };
    findBtn.addEventListener('click', find);
    search.addEventListener('input', () => { autoFilled = false; });
    search.addEventListener('keydown', (e) => { if (e.key === 'Enter') { e.preventDefault(); find(); } });

    FF.MapPicker.create(mapEl, {
      lat: null, lng: null, onPick,
      onEngine: (p) => { findBtn.hidden = !p.canGeocode; }
    }).then((picker) => {
      if (!body.isConnected) { picker.destroy(); return; }   // the dialog was closed while the map loaded
      this.picker = picker;
    });
  },

  // The text saved as the pickup location: the typed description first, then the map address
  pickupText(description) {
    const desc = String(description || '').trim();
    const addr = this.pickup && this.pickup.address ? this.pickup.address : '';
    if (desc || addr) return [desc, addr].filter(Boolean).join(' \u2014 ');
    return this.pickup ? `Pinned on map (${this.pickup.lat.toFixed(5)}, ${this.pickup.lng.toFixed(5)})` : '';
  },

  // Shrinks a photo and stores it where the owner app can show it. Returns '' when it cannot be uploaded.
  async uploadPhoto(file) {
    const sb = window.adminStore.client && window.adminStore.client();
    if (!sb || !file || !/^image\//.test(file.type || '')) return '';
    const bitmap = await createImageBitmap(file);
    const scale = Math.min(1, 900 / Math.max(bitmap.width, bitmap.height));
    const canvas = document.createElement('canvas');
    canvas.width = Math.round(bitmap.width * scale);
    canvas.height = Math.round(bitmap.height * scale);
    canvas.getContext('2d').drawImage(bitmap, 0, 0, canvas.width, canvas.height);
    const blob = await new Promise((resolve) => canvas.toBlob(resolve, 'image/jpeg', 0.82));
    if (!blob) return '';
    const path = `impounds/${crypto.randomUUID()}.jpg`;
    const { error } = await sb.storage.from('sighting-photos').upload(path, blob, { contentType: 'image/jpeg' });
    if (error) throw error;
    return sb.storage.from('sighting-photos').getPublicUrl(path).data.publicUrl || '';
  },

  async submit(form) {
    const d = this.draft;
    if (!d || d.alreadyHeld) return;
    const home = window.adminStore.getMyShelter();
    if (!home) { window.adminApp.showToast('Add your facility first.', 'warning'); return; }
    const data = new FormData(form);
    const btn = this.root && this.root.querySelector('#in-submit');
    if (btn) btn.disabled = true;

    let photoUrl = d.photoUrl || '';
    const file = data.get('photo');
    if (file && file.size) {
      if (btn) btn.textContent = 'Uploading photo…';
      let uploaded = '';
      try { uploaded = await this.uploadPhoto(file); } catch (e) { uploaded = ''; }
      if (!uploaded) {
        // A photo is required, so never log the pet without it
        window.adminApp.showToast('The photo could not be uploaded. Check the connection and try again.', 'error');
        if (btn) { btn.disabled = false; btn.textContent = 'Log intake'; }
        return;
      }
      photoUrl = uploaded;
    }
    if (!photoUrl) {
      window.adminApp.showToast('Add a photo of the pet to log the intake.', 'warning');
      if (btn) btn.disabled = false;
      return;
    }
    const chosen = this.facilities().find(s => s.id === (data.get('shelterId') || this.facilityId)) || home;

    const record = window.adminStore.saveImpoundment({
      petId: d.petId,
      petName: data.get('petName'),
      rfidTag: d.tag || '',
      species: data.get('species') || d.species,
      breed: data.get('breed') || undefined,
      age: data.get('age') || undefined,
      shelterId: chosen.id,
      shelterName: chosen.name,
      shelterAddress: chosen.address || '',
      shelterPhone: chosen.phone || '',
      cageNumber: data.get('cageNumber'),
      impoundLocation: this.pickupText(data.get('placeDescription')),
      impoundLat: this.pickup ? this.pickup.lat : undefined,
      impoundLng: this.pickup ? this.pickup.lng : undefined,
      intakeOfficer: data.get('intakeOfficer'),
      healthCondition: data.get('healthCondition') || 'Normal upon intake assessment.',
      intakeDate: d.intakeAt,
      claimDeadline: d.claimDeadline,
      photoUrl
    });

    window.adminApp.showToast(`Logged intake for ${record.petName} at ${chosen.name}. 72h countdown started.`, 'success');
    this.close();
    window.adminApp.renderView('impoundments');
  },

  // ===== NFC: tap a tag on this device (Web NFC: Chrome on Android, over HTTPS) =====
  isBrave() {
    return !!(navigator.brave && typeof navigator.brave.isBrave === 'function');
  },

  nfcSupported() {
    return 'NDEFReader' in window && !this.isBrave();
  },

  // Why this device cannot scan, in the same words as the owner app
  unsupportedText() {
    if (this.isBrave()) return 'Brave does not support NFC scanning. Open this page in Chrome on Android to scan tags, or type the tag code below.';
    if (window.isSecureContext === false) return 'NFC scanning needs a secure (HTTPS) page. Open the console over HTTPS, or type the tag code below.';
    return 'This device cannot read NFC tags (Web NFC works in Chrome on Android over HTTPS). Type the tag code below instead.';
  },

  setNfc(state, text) {
    this.nfc = { state, text: text || '' };
    this.paintNfc();
  },

  paintNfc() {
    const scope = this.root || document;
    const box = scope.querySelector('#in-nfc');
    const btn = scope.querySelector('#in-nfc-btn');
    const scanning = this.nfc.state === 'scanning';
    if (box) {
      box.hidden = this.nfc.state === 'idle';
      box.setAttribute('data-state', this.nfc.state);
      const span = box.querySelector('span');
      if (span) span.textContent = this.nfc.text;
    }
    if (btn) {
      btn.setAttribute('aria-pressed', String(scanning));
      const label = btn.querySelector('span');
      if (label) label.textContent = scanning ? 'Stop' : 'Tap NFC';
    }
  },

  // The dialog box is reused by other dialogs, so "open" means our own content is still in it and it is showing
  isOpen() {
    const backdrop = document.getElementById('app-modal-backdrop');
    return !!(this.root && this.root.querySelector('#in-body') && (!backdrop || backdrop.classList.contains('open')));
  },

  // Once a pet is on the form the reader is switched off, so nothing more is read until "Scan again" is pressed
  holdNfc() {
    this.stopNfc();
  },

  stopNfc() {
    this.locked = false;
    if (this._abort) { this._abort.abort(); this._abort = null; }
    if (this.nfc.state !== 'idle') this.setNfc('idle');
  },

  async startNfc() {
    if (!this.nfcSupported()) {
      this.setNfc('error', this.unsupportedText());
      return;
    }
    this.stopNfc();
    const abort = new AbortController();
    this._abort = abort;
    this.setNfc('scanning', 'Hold a tag to the back of your device…');
    try {
      const reader = new NDEFReader();
      let permission = 'unknown';
      try { permission = (await navigator.permissions.query({ name: 'nfc' })).state; } catch (e) { /* not queryable */ }
      if (permission === 'denied') { this.setNfc('error', 'NFC permission was denied. Allow NFC for this site and try again.'); this._abort = null; return; }
      const started = reader.scan({ signal: abort.signal });
      started.catch(() => {});
      if (permission === 'granted') {
        // With permission in place scanning starts at once; if not, NFC is switched off on the device
        const timedOut = await Promise.race([started.then(() => false), new Promise((resolve) => setTimeout(() => resolve(true), 5000))]);
        if (timedOut) { abort.abort(); this._abort = null; this.setNfc('error', 'NFC scanning did not start. Turn NFC on in your phone settings and try again.'); return; }
      } else {
        await started; // waits for the permission prompt
      }
      if (abort.signal.aborted) return;
      reader.addEventListener('reading', (event) => {
        // The dialog was closed while a read was on its way
        if (abort.signal.aborted || !this.isOpen()) { this.stopNfc(); return; }
        if (this.locked) return; // a pet is already on the form
        const payload = this.parseTag(event.message, event.serialNumber);
        if (!payload) { this.setNfc('scanning', 'That tag has no ID. Try another tag.'); return; }
        if (navigator.vibrate) navigator.vibrate(30);
        this.showForm(payload);
      });
      reader.addEventListener('readingerror', () => {
        if (this.locked) return;
        this.setNfc('scanning', 'Could not read the tag. Hold it flat against the back of the device and keep still.');
        if (navigator.vibrate) navigator.vibrate(80);
      });
    } catch (err) {
      this._abort = null;
      if (err && err.name === 'AbortError') return;
      this.setNfc('error', err && err.name === 'NotAllowedError'
        ? 'NFC permission was denied. Allow NFC for this site and try again.'
        : ((err && err.message) || 'Could not start the NFC reader.'));
    }
  }
};
